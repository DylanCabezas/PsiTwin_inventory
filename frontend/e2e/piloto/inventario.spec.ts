import { test, expect, type Page } from '@playwright/test'
async function login(page: Page, email: string) {
  await page.goto('/login')
  await page.locator('input[name=correo]').fill(email)
  await page.locator('input[name=password]').fill('SIMULADO-Piloto-2026!')
  await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
  await page.waitForURL(url => !url.pathname.includes('/login'))
  await page.goto('/inventario')
  await expect(page.getByRole('link', { name: 'Arroz', exact: true }).filter({ visible: true }).first()).toBeVisible()
}
test('company sees rack stock, filters and the correct detail history', async ({ page }, info) => {
  await login(page, 'piloto.simulado@gmail.com')
  await expect(page.getByRole('button', { name: 'Todos 10', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Nuevo inventario', exact: true })).toHaveCount(0)
  await expect(page.getByText('Aún no hay inventarios', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: /Stock bajo/ }).click()
  await expect(page.getByRole('link', { name: 'Azúcar', exact: true }).filter({ visible: true }).first()).toBeVisible()
  await page.getByRole('button', { name: /Sin stock/ }).click()
  await expect(page.getByRole('link', { name: 'Aceite', exact: true }).filter({ visible: true }).first()).toBeVisible()
  await expect(page.getByRole('link', { name: 'Arroz', exact: true }).filter({ visible: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Todos 10', exact: true }).click()
  const history = page.waitForResponse(r => r.url().includes('/detalles-inventario/') && r.url().endsWith('/historial'))
  await page.getByRole('button', { name: 'Historial de Arroz', exact: true }).filter({ visible: true }).first().click()
  expect((await history).status()).toBe(200)
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.screenshot({ path: `../artifacts/inventario-corregido.local/${info.project.name}.png`, fullPage: true })
  await page.reload()
  await expect(page.getByRole('button', { name: 'Todos 10', exact: true })).toBeVisible()
})

test('operator creates and edits a detail, registers a sale and deletes an empty detail', async ({ page }, info) => {
  test.skip(info.project.name !== 'desktop', 'Write flow covered once; read and filters run on desktop and mobile')
  await login(page, 'operario.piloto@example.com')
  const token = await page.evaluate(() => localStorage.getItem('psitwin.token'))
  const headers = { Authorization: `Bearer ${token}` }
  const initial = await (await page.request.get('/api/v1/detalles-inventario', { headers })).json()
  const products = await (await page.request.get('/api/v1/productos', { headers })).json()
  const rice = products.find((p: {nombre: string}) => p.nombre === 'Arroz')
  const existing = initial.find((d: {id_producto: string}) => d.id_producto === rice.id_producto)
  await page.getByRole('button', { name: 'Nuevo inventario', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox', { name: 'Producto', exact: true }).selectOption(rice.id_producto)
  const warehouse = dialog.getByRole('combobox', { name: 'Almacén', exact: true })
  if (await warehouse.isEnabled()) await warehouse.selectOption({ label: 'Almacén principal SIMULADO revisado' })
  const zone = dialog.getByRole('combobox', { name: 'Zona', exact: true })
  await zone.selectOption(await zone.locator('option').filter({ hasText: 'Bebidas SIMULADO' }).getAttribute('value') as string)
  const rack = dialog.getByRole('combobox', { name: 'Rack', exact: true })
  const rackId = await rack.locator('option').filter({ hasText: 'A-02' }).getAttribute('value')
  await rack.selectOption(rackId!)
  await dialog.getByRole('spinbutton', { name: 'Stock inicial', exact: true }).fill('0')
  await dialog.getByRole('spinbutton', { name: 'Stock mínimo', exact: true }).fill('0')
  await dialog.getByRole('spinbutton', { name: 'Stock máximo', exact: true }).fill('20')
  const createdResponse = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/detalles-inventario'))
  await dialog.getByRole('button', { name: 'Crear inventario', exact: true }).click()
  const created = await (await createdResponse).json()
  expect(created.id_detalle_inventario).not.toBe(existing.id_detalle_inventario)
  expect(created.id_inventario).toBe(existing.id_inventario)
  await expect(dialog).not.toBeVisible()
  const row = page.locator('tr').filter({ hasText: 'Arroz' }).filter({ hasText: 'A-02' })
  await row.getByRole('button', { name: 'Editar límites de Arroz', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('spinbutton', { name: 'Stock máximo', exact: true }).fill('30')
  const updatedResponse = page.waitForResponse(r => r.request().method() === 'PUT' && r.url().endsWith('/detalles-inventario/' + created.id_detalle_inventario))
  await dialog.getByRole('button', { name: 'Guardar límites', exact: true }).click()
  expect((await updatedResponse).status()).toBe(200)
  await expect(dialog).not.toBeVisible()
  await page.goto('/movimientos')
  await page.getByRole('button', { name: 'Registrar salida', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox', { name: 'Producto', exact: true }).selectOption(rice.id_producto)
  await dialog.getByRole('combobox', { name: 'Ubicación (inventario)', exact: true }).selectOption(existing.id_detalle_inventario)
  await dialog.getByRole('spinbutton', { name: 'Cantidad', exact: true }).fill('1')
  const saleResponse = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/movimientos'))
  await dialog.getByRole('button', { name: 'Registrar salida', exact: true }).click()
  const sale = await saleResponse
  expect(sale.status()).toBe(201)
  expect(sale.request().postDataJSON()).toMatchObject({ id_inventario: existing.id_inventario, id_detalle_inventario: existing.id_detalle_inventario })
  expect((await sale.json()).stock_nuevo).toBe(existing.stock_actual - 1)
  await page.goto('/inventario')
  await page.locator('tr').filter({ hasText: 'Arroz' }).filter({ hasText: 'A-02' }).getByRole('button', { name: 'Eliminar inventario de Arroz', exact: true }).click()
  const removedResponse = page.waitForResponse(r => r.request().method() === 'DELETE' && r.url().endsWith('/detalles-inventario/' + created.id_detalle_inventario))
  await page.getByRole('dialog').getByRole('button', { name: 'Eliminar', exact: true }).click()
  expect((await removedResponse).status()).toBe(200)
  expect((await (await page.request.get('/api/v1/detalles-inventario', { headers })).json()).length).toBe(10)
})
