r"""Read-only checks. No credentials, user text, or audio are written to disk.

Run from backend: ..\.runtime.local\python\python.exe scripts/diagnosticar_saiki.py
"""
import asyncio
import argparse
import base64
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.config.settings import settings
from app.services.local_voice_service import LocalVoiceService


class ConnectedRequest:
    async def is_disconnected(self):
        return False


async def main(voice='em_santa'):
    # Existing cached models only: this diagnostic never downloads large files.
    os.environ['HF_HUB_OFFLINE'] = '1'
    service = LocalVoiceService()
    report = {'python_exists': Path(settings.saiki_voice_python).is_file(),
              'stt_model': settings.saiki_stt_model, 'tts_provider': settings.saiki_tts_provider, 'tts_voice': voice}
    try:
        speech = await service.execute({'operation': 'synthesize', 'text': 'Abre mi inventario y muestra los sensores.',
                                        'voice': voice, 'speed': 1}, ConnectedRequest())
        report['tts_bytes'] = len(base64.b64decode(speech['audio']))
        result = await service.execute({'operation': 'transcribe', 'audio': speech['audio']}, ConnectedRequest())
        report['stt_synthetic_fixture'] = result['text']
    except Exception as exc:
        report['voice_error'] = {'type': type(exc).__name__, 'status': getattr(exc, 'status_code', None)}
        # Repository fixture generated by TTS, never a user's microphone recording.
        fixture = Path(__file__).resolve().parents[2] / 'artifacts/saiki-em_santa.wav'
        if fixture.is_file():
            try:
                result = await service.execute({'operation': 'transcribe',
                    'audio': base64.b64encode(fixture.read_bytes()).decode()}, ConnectedRequest())
                report['stt_existing_synthetic_fixture'] = result['text']
            except Exception as stt_exc:
                report['stt_error'] = {'type': type(stt_exc).__name__, 'status': getattr(stt_exc, 'status_code', None)}
    finally:
        await service.close()
    from motor.motor_asyncio import AsyncIOMotorClient
    client = AsyncIOMotorClient(settings.mongodb_url, serverSelectionTimeoutMS=3000)
    try:
        await client.admin.command('ping')
        db = client[settings.mongodb_database]
        report['mongodb'] = 'connected'
        report['global_counts_not_tenant_counts'] = {name: await db[name].count_documents({})
            for name in ('dispositivos', 'productos', 'detalles_inventario', 'alertas')}
    except Exception as exc:
        report['mongodb'] = type(exc).__name__
    finally:
        client.close()
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--voice', choices=('em_santa', 'em_alex'), default='em_santa')
    asyncio.run(main(parser.parse_args().voice))
